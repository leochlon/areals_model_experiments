"""Writes figures/longrange.tex (Figure 3): why local flow equations have a global solution, why area-weighted attention can
represent it, and which training stage supplies the long range.

All three panels use the same 2D wing, cut into the same uneven patches (finer at the nose, as meshes are), and the
same query point x just above the upper surface.

(A) Physics. Line widths are the 2D double-layer kernel times patch length, |n_j . (x - y_j)| / |x - y_j|^2 * A_j,
    which is the angle patch j subtends at x: it grows with the patch's area, with how squarely it faces x, and
    falls with distance. Unit density; exact for the kernel, not a flow solution.
(B) Attention with and without the log-area bias, for one illustrative similarity exp(-d/lambda). Without areas the
    densely sampled nose takes weight in proportion to its number of samples; with areas, in proportion to its surface.
(C) Attention with weights A_j exp(-d_j/lambda), lambda fitted so that the share of weight beyond 0.5R (R the
    area-weighted RMS radius) equals the measured decoder shares on the 16 DoubleDelta test wings: 17% after
    pretraining and 40% after fine-tuning (Appendix K).

Usage: python3 make_longrange.py OUT.tex
"""
import math
import sys

AX, BX = 1.75, 0.48         # ellipse semi-axes (cm)
M = 24000
ANG = [2 * math.pi * k / M for k in range(M + 1)]
PTS = [(AX * math.cos(t), BX * math.sin(t)) for t in ANG]
S = [0.0]
for k in range(M):
    S.append(S[-1] + math.dist(PTS[k], PTS[k + 1]))
L = S[-1]
S_NOSE = S[M // 2]


def rho(u):
    """Sampling density along the wall: five times denser at the nose."""
    return 1 + 4.0 * math.exp(-((u - S_NOSE) ** 2) / (2 * 0.28 ** 2))


F = [0.0]
for k in range(M):
    F.append(F[-1] + rho(0.5 * (S[k] + S[k + 1])) * (S[k + 1] - S[k]))
N = 30
bounds, j = [], 0
for i in range(N + 1):
    t = F[-1] * i / N
    while j < M and F[j] < t:
        j += 1
    bounds.append(j)


def normal_at(p):
    nx, ny = p[0] / AX ** 2, p[1] / BX ** 2
    n = math.hypot(nx, ny)
    return nx / n, ny / n


patches = []
for i in range(N):
    k0, k1 = bounds[i], bounds[i + 1]
    area = S[k1] - S[k0]
    smid = 0.5 * (S[k0] + S[k1])
    km = min(range(k0, k1 + 1), key=lambda k: abs(S[k] - smid))
    y = PTS[km]
    step = max(1, (k1 - k0) // 10)
    poly = [PTS[k] for k in range(k0, k1, step)] + [PTS[k1]]
    patches.append({'area': area, 'y': y, 'n': normal_at(y), 'poly': poly})

TH = math.radians(108)
p0 = (AX * math.cos(TH), BX * math.sin(TH))
n0 = normal_at(p0)
X = (p0[0] + 0.28 * n0[0], p0[1] + 0.28 * n0[1])
D = [math.dist(X, p['y']) for p in patches]
AREA = [p['area'] for p in patches]
ctr = (sum(a * p['y'][0] for a, p in zip(AREA, patches)) / L, sum(a * p['y'][1] for a, p in zip(AREA, patches)) / L)
R = math.sqrt(sum(a * math.dist(p['y'], ctr) ** 2 for a, p in zip(AREA, patches)) / L)


def norm(w):
    s = sum(w)
    return [x / s for x in w]


def att(lam, use_area=True):
    return norm([(a if use_area else 1.0) * math.exp(-d / lam) for a, d in zip(AREA, D)])


def share_beyond(w):
    return sum(x for x, d in zip(w, D) if d > 0.5 * R)


def fit(target):
    lo, hi = 1e-3, 100.0
    for _ in range(200):
        mid = math.sqrt(lo * hi)
        lo, hi = (mid, hi) if share_beyond(att(mid)) < target else (lo, mid)
    return math.sqrt(lo * hi)


def f(v):
    return f"{v:.3f}"


def wing(ox, oy, w, color, shade_a, shade_b, circle=False, cap=2.7):
    """One wing at offset (ox, oy) with lines from the query to every patch, width proportional to w."""
    out = [f"\\fill[arealgrid] ({f(ox)},{f(oy)}) ellipse ({AX} and {BX});"]
    qx, qy = ox + X[0], oy + X[1]
    if circle:
        out.append(f"\\fill[arealrec, opacity=0.22] ({f(qx)},{f(qy)}) circle ({f(0.5 * R)});")
        out.append(f"\\draw[arealmuted, line width=0.5pt, dash pattern=on 2pt off 1.5pt] ({f(qx)},{f(qy)}) circle ({f(0.5 * R)});")
    wmax = max(w)
    for p, x in sorted(zip(patches, w), key=lambda t: t[1]):
        lw = cap * x / wmax
        if lw < 0.04:
            continue
        op = 0.3 + 0.65 * min(1.0, lw / 1.4)
        out.append(f"\\draw[{color}, line width={max(lw, 0.12):.2f}pt, opacity={op:.2f}] ({f(qx)},{f(qy)}) -- "
                   f"({f(ox + p['y'][0])},{f(oy + p['y'][1])});")
    for i, p in enumerate(patches):
        pts = ' -- '.join(f"({f(ox + a)},{f(oy + b)})" for a, b in p['poly'])
        out.append(f"\\draw[{shade_a if i % 2 else shade_b}, line width=2.1pt, line cap=butt] {pts};")
    out.append(f"\\fill[arealwarn] ({f(qx)},{f(qy)}) circle (1.8pt);")
    return out


def main(path):
    lines = [r"""% Generated by make_longrange.py; edit that script, not this file. See the script for what each line width means.
\begin{tikzpicture}[x=1cm, y=1cm, font=\footnotesize, execute at begin node={\hyphenpenalty=10000},
    ttl/.style={anchor=west, font=\small\bfseries, text=arealfg},
    lab/.style={inner sep=1pt, font=\scriptsize, text=arealmuted},
    ink/.style={inner sep=1pt, font=\scriptsize, text=arealfg},
    hd/.style={inner sep=1pt, font=\scriptsize\bfseries, text=arealfg},
    flow/.style={-{Stealth[length=4pt,width=3.4pt]}, line width=0.6pt, draw=arealfg},
    call/.style={draw=arealmuted, line width=0.4pt}]"""]
    # ------------------------------------------------------------------ A
    ax, ay = 2.75, 0.85
    lines.append(r"\node[ttl] at (0,4.25) {A\quad Local equations, global flow};")
    kern = [a * abs(p['n'][0] * (X[0] - p['y'][0]) + p['n'][1] * (X[1] - p['y'][1])) / d ** 2
            for a, p, d in zip(AREA, patches, D)]
    lines += wing(ax, ay, kern, 'arealfg', 'arealmuted!75', 'arealmuted!35')
    # callouts: the nearest facing patch, a far patch and an edge-on patch
    near = max(range(N), key=lambda i: kern[i])
    far = max(range(N), key=lambda i: D[i])
    cos = [abs(p['n'][0] * (X[0] - p['y'][0]) + p['n'][1] * (X[1] - p['y'][1])) / d for p, d in zip(patches, D)]
    graze = min([i for i in range(N) if patches[i]['y'][1] > 0 and patches[i]['y'][0] > X[0] + 0.6 and D[i] < 1.5],
                key=lambda i: cos[i])
    for i, txt, dx, dy, anc in [(near, 'near: heavy', 1.0, 1.05, 'west'),
                                (graze, 'seen edge-on: light', 0.15, 0.62, 'south west'),
                                (far, 'far: light', -0.05, -0.55, 'north')]:
        y = patches[i]['y']
        px, py = ax + y[0], ay + y[1]
        lines.append(f"\\draw[call] ({f(px)},{f(py)}) -- ({f(px + dx)},{f(py + dy)}) node[lab, anchor={anc}] {{{txt}}};")
    lines.append(f"\\node[ink, anchor=south] at ({f(ax + X[0])},{f(ay + X[1] + 0.05)}) {{$x$}};")
    # inset: each point's equation links only neighbours
    cx, cy, r = 0.55, 3.35, 0.42
    lines.append(f"\\draw[arealmuted, line width=0.5pt, fill=white] ({cx},{cy}) circle ({r});")
    for ddx, ddy in [(-0.2, 0), (0.2, 0), (0, -0.2), (0, 0.2)]:
        lines.append(f"\\draw[arealfg, line width=0.6pt] ({cx},{cy}) -- ({cx + ddx:.2f},{cy + ddy:.2f});")
        lines.append(f"\\fill[arealfg] ({cx + ddx:.2f},{cy + ddy:.2f}) circle (1.1pt);")
    lines.append(f"\\fill[arealwarn] ({cx},{cy}) circle (1.5pt);")
    lines.append(f"\\node[lab, anchor=west, align=left] at ({cx + r + 0.08:.2f},{cy + 0.12:.2f}) "
                 "{the Euler--Lagrange equation at\\\\each point links only neighbours};")
    lines.append(f"\\draw[flow] ({cx + 0.1:.2f},{cy - r - 0.02:.2f}) to[out=-80, in=180] "
                 f"({f(ax + X[0] - 0.12)},{f(ay + X[1] + 0.02)});")
    lines.append(f"\\node[lab, anchor=north west] at ({cx + 0.2:.2f},{cy - r - 0.12:.2f}) {{solved together}};")
    lines.append(r"""\node[lab, anchor=north west, text width=5.15cm, align=left] at (0.1,-0.25)
  {Each point's Euler--Lagrange equation links it only to its neighbours, yet solving them together makes the flow at $x$ a sum over
   the whole wall: each patch counts by its area, how squarely it faces $x$ and how near it is.};""")
    # ------------------------------------------------------------------ B
    bx = 5.75
    lines.append(f"\\node[ttl] at ({bx},4.25) {{B\\quad Attention sums over the surface}};")
    lam_b = 2.5
    plain, weighted = att(lam_b, use_area=False), att(lam_b, use_area=True)
    nose = [i for i in range(N) if patches[i]['y'][0] < -1.15]
    sp, sw = sum(plain[i] for i in nose), sum(weighted[i] for i in nose)
    for oy, head, sub, w in [(2.45, 'without areas', 'the finely cut nose dominates', plain),
                             (0.45, 'with areas', 'each token counts by its patch', weighted)]:
        lines += wing(bx + 2.75, oy, w, 'arealteal', 'arealteal!80', 'arealteal!40')
        lines.append(f"\\node[hd, anchor=south west] at ({f(bx + 2.95)},{f(oy + 1.05)}) {{{head}}};")
        lines.append(f"\\node[lab, anchor=north west] at ({f(bx + 2.95)},{f(oy + 1.05)}) {{{sub}}};")
    lines.append(f"""\\node[lab, anchor=north west, text width=5.15cm, align=left] at ({bx + 0.1},-0.25)
  {{Each token stands for a patch of wall. With its log area in the logit, its weight is that area times a learned
   similarity of position and normal: attention averages over the surface, like the sum in A, and a ninefold change in
   sampling moves predictions 81.5\\% less.}};""")
    # ------------------------------------------------------------------ C
    cx0 = 11.5
    lines.append(f"\\node[ttl] at ({cx0},4.25) {{C\\quad Simulations teach the reach}};")
    wp, wf = att(fit(0.17)), att(fit(0.40))
    for oy, head, sub, w in [(2.45, 'after pretraining', '17\\% beyond $0.5R$', wp),
                             (0.45, 'after fine-tuning', '40\\% beyond $0.5R$', wf)]:
        lines += wing(cx0 + 2.75, oy, w, 'arealteal', 'arealteal!80', 'arealteal!40', circle=True)
        lines.append(f"\\node[hd, anchor=south west] at ({f(cx0 + 2.95)},{f(oy + 1.05)}) {{{head}}};")
        lines.append(f"\\node[lab, anchor=north west] at ({f(cx0 + 2.95)},{f(oy + 1.05)}) {{{sub}}};")
    lines.append(f"""\\node[lab, anchor=north west, text width=5.15cm, align=left] at ({cx0 + 0.1},-0.25)
  {{Pretraining keeps attention near $x$ (dashed: half the RMS radius $R$), enough to read the local geometry.
   Fine-tuning on simulations spreads it over the wall, on every test wing: the long range in A is learned from
   simulations.}};""")
    lines.append(r"\end{tikzpicture}")
    open(path, 'w').write('\n'.join(lines) + '\n')
    print(f"R={R:.3f}; nose share without/with areas {sp:.3f}/{sw:.3f}; "
          f"C shares {share_beyond(wp):.3f}/{share_beyond(wf):.3f}; patches {N}, nose patches {len(nose)}; "
          f"areas {min(AREA):.3f}-{max(AREA):.3f}", file=sys.stderr)


if __name__ == '__main__':
    main(sys.argv[1])
