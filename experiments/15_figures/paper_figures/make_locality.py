"""Writes figures/locality.tex (Figure 2): near the wall the flow equation sees the shape only through local geometry, the distance
to the wall encodes that geometry, and the pretrained decoder reads it with short-range attention.

(A) Two bodies that coincide on a patch around the foot point p of a point x give the same flow equation at x: in wall coordinates the
    flow's Lagrangian density sees the shape only through the surface metric g_S and the shape operator W at p.
(B) The level sets and steepest lines of the distance are the wall coordinates. Spacing along the wall is g_S;
    neighbouring normal lines spread by 1 + t*kappa at height t, which is W. Value and Hessian of the half squared
    distance (the wall and the normal line) are pretraining targets; the third derivative (W) is not (Lemma 1).
(C) The decoder answers queries with the distance and normal line at their foot points, attending mostly to nearby
    surfel tokens (position, normal, area). Line widths are illustrative; the 52% (3% if spread by area) is measured on
    the 16 DoubleDelta test wings (Appendix K). W is how fast the predicted normal lines turn.

Usage: python3 make_locality.py OUT.tex
"""
import math
import sys


def f(v):
    return f"{v:.3f}"


def smooth(u):
    u = min(1.0, max(0.0, u))
    return u * u * (3 - 2 * u)


def main(path):
    L = [r"""% Generated by make_locality.py; edit that script, not this file.
\begin{tikzpicture}[x=1cm, y=1cm, font=\footnotesize, execute at begin node={\hyphenpenalty=10000},
    ttl/.style={anchor=west, font=\small\bfseries, text=arealfg},
    lab/.style={inner sep=1pt, font=\scriptsize, text=arealmuted},
    ink/.style={inner sep=1pt, font=\scriptsize, text=arealfg},
    tlab/.style={inner sep=1pt, font=\scriptsize, text=arealteal},
    call/.style={draw=arealmuted, line width=0.4pt},
    flow/.style={-{Stealth[length=4pt,width=3.4pt]}, line width=0.6pt, draw=arealfg}]"""]

    # ------------------------------------------------------------------ A: same nearby wall, same flow equation
    L.append(r"\node[ttl] at (0,3.45) {A\quad Local Euler--Lagrange equation};")
    cx, cy, a, b = 2.6, 0.95, 1.7, 0.78
    thp = math.pi / 2

    def p1(t):
        return (cx + a * math.cos(t), cy + b * math.sin(t))

    def n1(t):
        nx, ny = math.cos(t) / a, math.sin(t) / b
        n = math.hypot(nx, ny)
        return nx / n, ny / n

    def p2(t):
        d = abs(math.atan2(math.sin(t - thp), math.cos(t - thp)))
        s = smooth((d - 0.42) / 0.55)
        delta = s * (0.34 * math.sin(t + 0.9) + 0.12 * math.cos(3 * t))
        x, y = p1(t)
        nx, ny = n1(t)
        return (x + delta * nx, y + delta * ny)

    ts = [2 * math.pi * k / 240 for k in range(241)]
    L.append("\\fill[arealgrid] " + " -- ".join(f"({f(x)},{f(y)})" for x, y in map(p1, ts)) + " -- cycle;")
    L.append("\\draw[arealmuted, line width=0.9pt, dash pattern=on 3pt off 2pt] "
             + " -- ".join(f"({f(x)},{f(y)})" for x, y in map(p2, ts)) + " -- cycle;")
    L.append("\\draw[arealfg, line width=1.2pt] " + " -- ".join(f"({f(x)},{f(y)})" for x, y in map(p1, ts)) + " -- cycle;")
    p = p1(thp)
    xq = (p[0], p[1] + 0.62)
    mid = (p[0], p[1] + 0.25)
    L.append(f"\\fill[arealrec, opacity=0.25] ({f(mid[0])},{f(mid[1])}) circle (0.62);")
    L.append(f"\\draw[arealteal, line width=0.7pt] ({f(mid[0])},{f(mid[1])}) circle (0.62);")
    # the shared patch, drawn over both outlines
    tp = [thp - 0.42 + 0.84 * k / 30 for k in range(31)]
    L.append("\\draw[arealteal, line width=2.2pt] " + " -- ".join(f"({f(x)},{f(y)})" for x, y in map(p1, tp)) + ";")
    L.append(f"\\draw[arealfg, line width=0.5pt, dash pattern=on 1.5pt off 1pt] ({f(p[0])},{f(p[1])}) -- ({f(xq[0])},{f(xq[1])});")
    L.append(f"\\fill[arealfg] ({f(p[0])},{f(p[1])}) circle (1.4pt);")
    L.append(f"\\fill[arealwarn] ({f(xq[0])},{f(xq[1])}) circle (1.8pt);")
    L.append(f"\\node[ink, anchor=east] at ({f(xq[0] - 0.08)},{f(xq[1])}) {{$x$}};")
    L.append(f"\\node[ink, anchor=north east] at ({f(p[0] - 0.05)},{f(p[1] - 0.02)}) {{$p$}};")
    L.append(f"\\draw[call] ({f(mid[0] + 0.62)},{f(mid[1] + 0.05)}) -- ({f(mid[0] + 0.95)},{f(mid[1] + 0.05)}) "
             "node[tlab, anchor=west, align=left] {the Euler--Lagrange\\\\equation at $x$ uses\\\\only this wall};")
    q = p2(math.radians(205))
    L.append(f"\\draw[call] ({f(q[0])},{f(q[1])}) -- ({f(q[0] - 0.3)},{f(q[1] - 0.55)}) "
             "node[lab, anchor=north] {another body};")
    L.append(r"""\node[lab, anchor=north west, text width=5.2cm, align=left] at (0.1,-0.4)
  {In wall coordinates the Euler--Lagrange equation at $x$ depends on the shape only through how the wall measures
   length ($g_S$) and how it bends ($W$) at $p$, the wall point nearest $x$. Two bodies with the same wall near $p$ have
   the same equation at $x$, though not the same flow (\cref{fig:attention}).};""")

    # ------------------------------------------------------------------ B: distance draws the local geometry
    ox = 5.75
    L.append(f"\\node[ttl] at ({ox},3.45) {{B\\quad Distance draws the local geometry}};")
    c = (ox + 2.75, -3.25)
    r0 = 3.45
    ang = lambda d: math.radians(d)

    def pol(r, deg):
        return (c[0] + r * math.cos(ang(deg)), c[1] + r * math.sin(ang(deg)))

    def arc(r, d0, d1, n=60):
        return " -- ".join(f"({f(x)},{f(y)})" for x, y in (pol(r, d0 + (d1 - d0) * k / n) for k in range(n + 1)))

    L.append("\\fill[arealgrid] " + arc(r0, 63, 117) + f" -- ({f(pol(r0 - 0.3, 117)[0])},{f(pol(r0 - 0.3, 117)[1])})"
             f" -- ({f(pol(r0 - 0.3, 63)[0])},{f(pol(r0 - 0.3, 63)[1])}) -- cycle;")
    for t in (0.6, 1.2, 1.8):
        L.append(f"\\draw[arealteal, line width=0.55pt, opacity=0.7] {arc(r0 + t, 67, 113)};")
    top = 2.05
    for d in (71, 79, 101, 109):
        L.append(f"\\draw[arealmuted!60, line width=0.45pt] ({f(pol(r0, d)[0])},{f(pol(r0, d)[1])}) -- "
                 f"({f(pol(r0 + top, d)[0])},{f(pol(r0 + top, d)[1])});")
    for d in (85, 95):
        L.append(f"\\draw[arealteal, line width=1.2pt] ({f(pol(r0, d)[0])},{f(pol(r0, d)[1])}) -- "
                 f"({f(pol(r0 + top, d)[0])},{f(pol(r0 + top, d)[1])});")
    L.append(f"\\draw[arealfg, line width=1.3pt] {arc(r0, 63, 117)};")
    tb = 2.05
    ba, bb = pol(r0 + tb, 95), pol(r0 + tb, 85)
    L.append(f"\\draw[arealfg, line width=0.5pt, {{|[width=4pt]}}-{{|[width=4pt]}}] ({f(ba[0])},{f(ba[1])}) -- ({f(bb[0])},{f(bb[1])});")
    L.append(f"\\node[ink, anchor=south] at ({f(0.5 * (ba[0] + bb[0]))},{f(ba[1] + 0.08)}) {{$(1+t\\kappa)\\,\\Delta s$}};")
    wa, wb = pol(r0 + 0.12, 95), pol(r0 + 0.12, 85)
    L.append(f"\\draw[arealfg, line width=0.5pt, {{|[width=3pt]}}-{{|[width=3pt]}}] ({f(wa[0])},{f(wa[1])}) -- ({f(wb[0])},{f(wb[1])});")
    L.append(f"\\node[ink, anchor=south] at ({f(0.5 * (wa[0] + wb[0]))},{f(wa[1] + 0.02)}) {{$\\Delta s$}};")
    nl = pol(r0 + 1.45, 95)
    L.append(f"\\draw[call] ({f(nl[0])},{f(nl[1])}) -- ({f(nl[0] - 0.9)},{f(nl[1] + 0.55)}) "
             "node[tlab, anchor=east, align=right] {normal line\\\\(a target)};")
    sp = (bb[0], bb[1])
    L.append(f"\\draw[call] ({f(sp[0] + 0.05)},{f(sp[1])}) -- ({f(sp[0] + 0.55)},{f(sp[1] - 0.2)}) "
             "node[lab, anchor=west, align=left] {spreading: $W$\\\\(not a target)};")
    lv = pol(r0 + 1.2, 113)
    L.append(f"\\node[lab, anchor=east] at ({f(lv[0] - 0.05)},{f(lv[1])}) {{levels of $d$}};")
    wl = pol(r0, 117)
    L.append(f"\\node[lab, anchor=east, align=right] at ({f(wl[0] - 0.06)},{f(wl[1] + 0.2)}) {{$d=0$:\\\\the wall}};")
    gs = pol(r0 + 0.12, 90)
    L.append(f"\\draw[call] ({f(gs[0] + 0.33)},{f(gs[1] + 0.03)}) -- ({f(gs[0] + 1.15)},{f(gs[1] + 0.1)}) "
             "node[lab, anchor=west] {spacing: $g_S$};")
    L.append(r"""\node[lab, anchor=north west, text width=5.2cm, align=left] at (""" + f(ox + 0.1) + r""",-0.4)
  {The distance to the wall draws these coordinates. Its zero level is the wall and its steepest lines are the normal
   lines, the two pretraining targets; spacing along the wall is $g_S$, and the spreading of the normal lines is $W$,
   never a target (\cref{lem:primitive}).};""")

    # ------------------------------------------------------------------ C: pretraining reads it locally
    ox = 11.5
    L.append(f"\\node[ttl] at ({ox},3.45) {{C\\quad Pretraining reads it locally}};")
    c = (ox + 2.75, -3.9)
    r0 = 4.2

    def polc(r, deg):
        return (c[0] + r * math.cos(ang(deg)), c[1] + r * math.sin(ang(deg)))

    def arcc(r, d0, d1, n=60):
        return " -- ".join(f"({f(x)},{f(y)})" for x, y in (polc(r, d0 + (d1 - d0) * k / n) for k in range(n + 1)))

    L.append("\\fill[arealgrid] " + arcc(r0, 62, 118) + f" -- ({f(polc(r0 - 0.3, 118)[0])},{f(polc(r0 - 0.3, 118)[1])})"
             f" -- ({f(polc(r0 - 0.3, 62)[0])},{f(polc(r0 - 0.3, 62)[1])}) -- cycle;")
    L.append(f"\\draw[arealfg, line width=1.2pt] {arcc(r0, 62, 118)};")
    tok = [(64.5, 0.30), (68.5, 0.22), (72.5, 0.27), (76.5, 0.21), (80.5, 0.28), (84.5, 0.22), (88.5, 0.26),
           (92.5, 0.21), (96.5, 0.28), (100.5, 0.22), (104.5, 0.27), (108.5, 0.21), (112.5, 0.28), (116, 0.22)]
    queries = [(102, 0.5), (90, 0.45), (78, 0.55)]
    for qd, qt in queries:
        qp = polc(r0 + qt, qd)
        ws = [area * math.exp(-math.dist(qp, polc(r0, td)) / 0.24) for td, area in tok]
        wmax = max(ws)
        for (td, area), w in sorted(zip(tok, ws), key=lambda z: z[1]):
            lw = 2.3 * w / wmax
            if lw < 0.15:
                continue
            tp_ = polc(r0, td)
            L.append(f"\\draw[arealteal, line width={lw:.2f}pt, opacity={0.35 + 0.6 * min(1, lw / 1.2):.2f}] "
                     f"({f(qp[0])},{f(qp[1])}) -- ({f(tp_[0])},{f(tp_[1])});")
    for td, area in tok:
        tp_ = polc(r0, td)
        tx, ty = -math.sin(ang(td)), math.cos(ang(td))
        nx, ny = math.cos(ang(td)), math.sin(ang(td))
        h = area / 2
        L.append(f"\\draw[arealteal, line width=2.0pt, line cap=round] ({f(tp_[0] - h * tx)},{f(tp_[1] - h * ty)}) -- "
                 f"({f(tp_[0] + h * tx)},{f(tp_[1] + h * ty)});")
        L.append(f"\\draw[arealteal, line width=0.6pt] ({f(tp_[0])},{f(tp_[1])}) -- ({f(tp_[0] + 0.2 * nx)},{f(tp_[1] + 0.2 * ny)});")
    outs = []
    for qd, qt in queries:
        qp = polc(r0 + qt, qd)
        fp = polc(r0, qd)
        nx, ny = math.cos(ang(qd)), math.sin(ang(qd))
        L.append(f"\\draw[arealfg, line width=0.5pt, dash pattern=on 1.5pt off 1pt] ({f(fp[0])},{f(fp[1])}) -- ({f(qp[0])},{f(qp[1])});")
        a0 = (qp[0] + 0.55 * nx, qp[1] + 0.55 * ny)
        a1 = (qp[0] - 0.1 * nx, qp[1] - 0.1 * ny)
        L.append(f"\\draw[arealwarn, line width=1.1pt] ({f(a1[0])},{f(a1[1])}) -- ({f(a0[0])},{f(a0[1])});")
        L.append(f"\\fill[arealwarn] ({f(qp[0])},{f(qp[1])}) circle (1.7pt);")
        outs.append(a0)
    qm = polc(r0 + queries[1][1], queries[1][0])
    L.append(f"\\draw[arealmuted, line width=0.5pt, dash pattern=on 2pt off 1.5pt] ({f(qm[0])},{f(qm[1])}) circle (0.62);")
    L.append(f"\\draw[call] ({f(qm[0] + 0.44)},{f(qm[1] + 0.44)}) -- ({f(qm[0] + 1.25)},{f(qm[1] + 1.55)}) "
             "node[lab, anchor=south, align=center] {52\\% of attention\\\\within $0.25R$};")
    L.append(f"\\draw[arealmuted, line width=0.5pt, -{{Stealth[length=3pt]}}] ({f(outs[0][0])},{f(outs[0][1] + 0.08)}) "
             f"to[bend left=30] ({f(outs[2][0])},{f(outs[2][1] + 0.08)});")
    topm = max(o[1] for o in outs)
    L.append(f"\\node[lab, anchor=south east, align=right] at ({f(qm[0] - 0.05)},{f(topm + 0.42)}) {{the lines turn:\\\\$W$, not a target}};")
    tl = polc(r0, 116)
    L.append(f"\\draw[call] ({f(tl[0])},{f(tl[1] + 0.05)}) -- ({f(ox + 0.5)},{f(1.0)}) "
             "node[tlab, anchor=south, align=center] {token: position,\\\\normal, area};")
    L.append(r"""\node[lab, anchor=north west, text width=5.2cm, align=left] at (""" + f(ox + 0.1) + r""",-0.4)
  {Each query (orange) gets the distance and normal line at its nearest wall point from nearby tokens: 52\% of decoder attention
   lies within $0.25R$, against 3\% if spread by area. So at any point the decoder supplies the geometry the Euler--Lagrange equation needs.};""")
    L.append(r"\end{tikzpicture}")
    open(path, 'w').write('\n'.join(L) + '\n')


if __name__ == '__main__':
    main(sys.argv[1])
